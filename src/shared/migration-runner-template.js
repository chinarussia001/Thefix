export function buildMigrationRunnerSource(key) {
  if (typeof key !== "string" || !key.trim()) throw new Error("Migration key cannot be empty.");
  return `// Auto-generated by LovaRPM. Do not edit by hand.
// This route applies pending Drizzle migrations against the live DB using public.exec_sql.
// It is protected by a query-string key.

import { readdir, readFile } from "fs/promises";
import { join } from "path";
import { supabaseAdmin } from "@/integrations/supabase/client.server";

const RUNNER_KEY = ${JSON.stringify(key)};
const TRACKING_TABLE_SQL = "create table if not exists public._migrations_applied ( id text primary key, applied_at timestamptz not null default now() )";

export async function GET(request: Request) {
  const url = new URL(request.url);
  const key = url.searchParams.get("key");
  if (!key || key !== RUNNER_KEY) {
    return new Response(JSON.stringify({ ok: false, error: "unauthorized" }), {
      status: 401,
      headers: { "content-type": "application/json" },
    });
  }

  const { data: initData, error: initError } = await supabaseAdmin.rpc("exec_sql", {
    sql_text: TRACKING_TABLE_SQL,
  });
  if (initError || (initData && initData.ok === false)) {
    return new Response(JSON.stringify({
      ok: false,
      error: "init: " + (initError?.message ?? initData?.error ?? "unknown"),
    }), { status: 500, headers: { "content-type": "application/json" } });
  }

  const dir = join(process.cwd(), "drizzle/migrations");
  let files: string[];
  try {
    files = (await readdir(dir)).filter((file) => file.endsWith(".sql")).sort();
  } catch (error) {
    return new Response(JSON.stringify({
      ok: false,
      error: "cannot read migrations folder: " + String(error),
    }), { status: 500, headers: { "content-type": "application/json" } });
  }

  const applied: string[] = [];
  const skipped: string[] = [];
  for (const file of files) {
    const { data: existing } = await supabaseAdmin
      .from("_migrations_applied")
      .select("id")
      .eq("id", file)
      .maybeSingle();
    if (existing) {
      skipped.push(file);
      continue;
    }

    const sql = await readFile(join(dir, file), "utf8");
    const { data, error } = await supabaseAdmin.rpc("exec_sql", { sql_text: sql });
    if (error || (data && data.ok === false)) {
      return new Response(JSON.stringify({
        ok: false,
        error: error?.message ?? data?.error ?? "unknown sql error",
        failed_at: file,
      }), { status: 500, headers: { "content-type": "application/json" } });
    }

    const { error: trackingError } = await supabaseAdmin.from("_migrations_applied").insert({ id: file });
    if (trackingError) {
      return new Response(JSON.stringify({ ok: false, error: trackingError.message, failed_at: file }), {
        status: 500,
        headers: { "content-type": "application/json" },
      });
    }
    applied.push(file);
  }

  return new Response(JSON.stringify({ ok: true, applied, skipped }), {
    status: 200,
    headers: { "content-type": "application/json" },
  });
}
`;
}
