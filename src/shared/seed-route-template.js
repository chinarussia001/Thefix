export function buildSeedRouteSource(key) {
  const runnerKey = String(key || "").trim().toLowerCase();
  if (!/^[a-f0-9]{64}$/.test(runnerKey)) throw new Error("Migration key must be 32-byte lowercase hex.");
  return `// Auto-generated by LovaRPM. One-shot seed route.
// Marks migrations that are already applied by inspecting the DB.

import { readdir, readFile } from "fs/promises";
import { join } from "path";
import { supabaseAdmin } from "@/integrations/supabase/client.server";

const RUNNER_KEY = "${runnerKey}";
const TRACKING_TABLE_SQL = "create table if not exists public._migrations_applied ( id text primary key, applied_at timestamptz not null default now() )";

function extractFirstObject(sql: string): string | null {
  const tableMatch = sql.match(/create\\s+table\\s+(?:if\\s+not\\s+exists\\s+)?(?:public\\.)?([a-z0-9_]+)/i);
  return tableMatch?.[1] || null;
}

export async function GET(request: Request) {
  const url = new URL(request.url);
  const key = url.searchParams.get("key");
  if (!key || key !== RUNNER_KEY) {
    return new Response(JSON.stringify({ ok: false, error: "unauthorized" }), {
      status: 401,
      headers: { "content-type": "application/json" },
    });
  }

  const { data: initData, error: initError } = await supabaseAdmin.rpc("exec_sql", {
    sql_text: TRACKING_TABLE_SQL,
  });
  if (initError || (initData && initData.ok === false)) {
    return new Response(JSON.stringify({
      ok: false,
      error: "no exec_sql",
      detail: initError?.message ?? initData?.error ?? null,
    }), { status: 200, headers: { "content-type": "application/json" } });
  }

  const dir = join(process.cwd(), "drizzle/migrations");
  const files = (await readdir(dir)).filter((file) => file.endsWith(".sql")).sort();
  const seeded: string[] = [];

  for (const file of files) {
    const { data: existing } = await supabaseAdmin
      .from("_migrations_applied")
      .select("id")
      .eq("id", file)
      .maybeSingle();
    if (existing) continue;

    const sql = await readFile(join(dir, file), "utf8");
    const target = extractFirstObject(sql);
    if (!target) continue;
    const probeSql = \`select exists (select 1 from information_schema.tables where table_schema = 'public' and table_name = '\${target}') as present\`;
    const { data } = await supabaseAdmin.rpc("exec_sql", { sql_text: probeSql });
    const present = Array.isArray(data) && data.length > 0 && data[0].present === true;
    if (present) {
      await supabaseAdmin.from("_migrations_applied").insert({ id: file });
      seeded.push(file);
    }
  }

  return new Response(JSON.stringify({ ok: true, seeded }), {
    status: 200,
    headers: { "content-type": "application/json" },
  });
}
`;
}
